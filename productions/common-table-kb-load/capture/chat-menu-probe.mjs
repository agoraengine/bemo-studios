import { chromium } from "playwright";
import path from "node:path";
import { fileURLToPath } from "node:url";
const HERE = path.dirname(fileURLToPath(import.meta.url));
const PROFILE = path.join(HERE, "..", "..", "..", "capture", ".auth", "profile");
const context = await chromium.launchPersistentContext(PROFILE, { headless: true, viewport: { width: 1440, height: 900 } });
const page = context.pages()[0] || (await context.newPage());
await page.goto("https://app.bemointel.ai/", { waitUntil: "networkidle" }).catch(() => {});
await page.waitForTimeout(3000);
const row = page.locator("text=Wrenfield Alliance Mission Re").first();
await row.hover();
await page.waitForTimeout(600);
const kebab = page.locator("text=more_vert").first();
await kebab.click();
await page.waitForTimeout(900);
await page.screenshot({ path: "/tmp/chat-menu.png" });
const overlay = await page.locator(".cdk-overlay-container").innerText().catch(() => "(no overlay)");
console.log("menu:", JSON.stringify(overlay));
await context.close();
